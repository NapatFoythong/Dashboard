export function translate(language: Language, text: string | undefined, ...values: (string | number)[]): string {
  const source = text ?? "";
  const translated = language === "en" ? EN_MESSAGES[source] ?? source : source;
  return translated.replace(/\{(\d+)\}/g, (placeholder, index) => values[Number(index)] === undefined ? placeholder : String(values[Number(index)]));
}
